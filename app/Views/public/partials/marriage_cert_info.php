                    <li><i class="fas fa-check text-success me-2"></i>Current Marriage: Notarized testimonial from a traditional chief, governor, or township commissioner affirming compliance with tribal customs.</li>
                    <li><i class="fas fa-check text-success me-2"></i>Delayed Marriage: Legal representation, evidence of cohabitation, joint property, children’s bio-data, family testimonials, and proof of marital intimacy.</li>
                    <li><i class="fas fa-check text-success me-2"></i>Proxy Marriage: Notarized request with proof of intimacy, bride’s consent, and parental approbation.</li>
                    <li><i class="fas fa-check text-success me-2"></i>Polygamous Marriage: Written request to MIA, proof of financial capacity, family support record, and notification of existing spouse(s).</li>
