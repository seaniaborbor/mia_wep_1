                    <ul class="list-unstyled">
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Submit written request to MIA, with identification (birth certificate, national ID card, or valid passport) and proof of financial capacity (e.g., bank statements).</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Provide record of family support (e.g., children’s education).</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>MIA notifies existing wife/wives via written, telephonic, or other means, convening a meeting of parties.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Pay LRA tax.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>If refused, MIA may sanction marriage with conditions (e.g., new domicile) or grant divorce with settlements (e.g., alimony, asset distribution). Certificate issued post-officiation.</li>
