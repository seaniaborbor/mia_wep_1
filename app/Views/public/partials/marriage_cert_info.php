                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Pay LRA tax, with receipt number recorded on the certificate as evidence of fiscal compliance.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Submit identification (birth certificate, national ID card, or valid passport) for both spouses.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Provide notarized testimonial from a traditional chief, governor, or township commissioner, attesting to the ceremony’s adherence to tribal customs.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>MIA verifies documentation and payment, issuing the certificate with the issuance date tied to the LRA receipt.</li>
                    </ul>
                </div>
            </div>
        </div>
        
