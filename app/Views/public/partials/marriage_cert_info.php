            <div id="collapseProxy" class="accordion-collapse collapse" aria-labelledby="headingProxy" data-bs-parent="#marriageCategoriesAccordion">
                <div class="accordion-body">
                    <p>A marriage where one or both parties are absent, represented by proxies, recognized under customary law for parties outside Liberia’s bailiwick, subject to notarized approbation.</p>
                    <ul class="list-unstyled">
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Absent partner submits notarized request with proof of intimacy (e.g., social media, remittances).</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Bride in Liberia provides notarized consent and parental or guardian approval (in loco parentis).</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Submit identification (birth certificate, national ID card, or valid passport).</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Pay LRA tax.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>MIA issues certificate, sent via Expedited Mail System (EMS) for absent partner’s notarized approval, then processes and files a note to file.</li>
                    </ul>
                </div>
            </div>
