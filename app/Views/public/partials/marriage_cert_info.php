                <div class="accordion-body">
                    <p>Registration of a marriage post-ceremony, often due to prior non-compliance with registration mandates, requiring probative evidence to establish the union nunc pro tunc.</p>
                    <ul class="list-unstyled">
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Engage a lawyer or law firm for legal representation, a sine qua non for processing.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Submit identification (birth certificate, national ID card, or valid passport) and evidence, including joint property deeds, cohabitation records, children’s bio-data (e.g., birth certificates, school records), testimonials from two family members, and notarized attestation from a traditional authority.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Provide proof of marital intimacy (e.g., social media exchanges, joint bank account).</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>Pay LRA tax.</li>
                        <li><i class="fas fa-arrow-right text-primary me-2"></i>MIA conducts due diligence to preclude incest, consanguinity, or underage marriage, issuing the certificate, potentially backdated.</li>
                    </ul>
                </div>
            </div>
