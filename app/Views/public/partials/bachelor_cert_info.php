            <p class="text-muted mb-3">
                The Bachelorhood Certificate is an official document issued by the Ministry of Internal Affairs (MIA) in Liberia. It confirms that a man is not currently married under either traditional or statutory (civil) law. This certificate is often required for purposes like applying for a passport in a single name, entering a new marriage, or meeting immigration requirements. It is issued under the MIA’s legal authority, ensuring compliance with Liberian laws governing marital status.
