                    </p>
                    <h6 class="text-primary mb-2">Steps to Obtain the Certificate</h6>
                    <ul class="list-unstyled">
                        <li>
                            <i class="fas fa-arrow-right text-primary me-2"></i>
                            <strong>Submit a Written Request</strong>: Send a formal request to the MIA’s Legal Bureau. While not mandatory, it’s highly recommended to work with a lawyer or law firm to ensure your application is complete and meets legal standards.
                        </li>
                        <li>
                            <i class="fas fa-arrow-right text-primary me-2"></i>
                            <strong>Provide Identification</strong>: Submit a valid birth certificate, national ID card, or passport. This document confirms your identity and is essential for the MIA’s records.
                        </li>
                        <li>
                            <i class="fas fa-arrow-right text-primary me-2"></i>
                            <strong>Submit a Notarized Affidavit</strong>: Provide a sworn statement (affidavit) signed before a notary public, attesting that you are not currently married. This legal attestation is a key part of proving your bachelor status.
                        </li>
                        <li>
                            <i class="fas fa-arrow-right text-primary me-2"></i>
                            <strong>Include Proof of Ended Marriage (if applicable)</strong>: If you were previously married, you must show that the marriage has ended by providing a divorce certificate (for divorce cases) or a death certificate (if your spouse passed away).
                        </li>
                        <li>
                            <i class="fas fa-arrow-right text-primary me-2"></i>
                            <strong>Pay the LRA Tax</strong>: Make a tax payment to the Liberia Revenue Authority (LRA). The receipt number is recorded on the certificate, serving as evidence of fiscal compliance with Liberian regulations.
                        </li>
                        <li>
                            <i class="fas fa-arrow-right text-primary me-2"></i>
                            <strong>MIA Verification and Issuance</strong>: The MIA conducts due diligence to confirm you have no active traditional or statutory marriages. This involves checking national records and ensuring statutory verification of your single status. Once verified, the MIA issues the certificate, which includes the LRA receipt number for authenticity.
