                    <li><i class="fas fa-check text-success me-2"></i><strong>Payment</strong>: A tax payment receipt from the Liberia Revenue Authority (LRA), which is required for issuing the certificate. The receipt number is recorded on the document.</li>
                    <li><i class="fas fa-check text-success me-2"></i><strong>Affidavit</strong>: A notarized affidavit (a sworn statement signed before a notary public) declaring that you are not married.</li>
                    <li><i class="fas fa-check text-success me-2"></i><strong>Previous Marriage (if applicable)</strong>: If you were previously married, you must provide a divorce certificate or the death certificate of your deceased spouse to prove the marriage has ended.</li>
