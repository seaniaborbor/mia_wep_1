            <p class="text-muted mb-3">
                The Spinsterhood Certificate is an official document issued by the Ministry of Internal Affairs (MIA) in Liberia. It confirms that a woman is not currently married under either traditional or statutory (civil) law. This certificate is often required for purposes such as applying for a passport in a maiden name, entering a new marriage, or meeting immigration requirements abroad. Issued under the MIA’s legal authority, it ensures compliance with Liberian laws governing marital status, providing formal proof of a woman’s single status.
